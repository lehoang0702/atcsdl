DEFINE v_app_user = '&1'
DEFINE v_app_pass = '&2'
DEFINE v_bf_user  = '&3'
DEFINE v_bf_pass  = '&4'

-- 1. Profile cho tài khoản thử nghiệm Brute-force (KB2) không bị khóa sau 10 lần sai
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM dba_profiles WHERE profile = 'LAB_BF_PROFILE';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE PROFILE LAB_BF_PROFILE LIMIT
        FAILED_LOGIN_ATTEMPTS UNLIMITED
        PASSWORD_LIFE_TIME UNLIMITED
    ';
  END IF;
END;
/

-- 2. Đảm bảo tài khoản ứng dụng (chứa schema STUDENTS, GRADES) tồn tại
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM dba_users WHERE username = UPPER('&v_app_user');
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER ' || '&v_app_user' || ' IDENTIFIED BY "' || '&v_app_pass' || '" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP';
  ELSE
    EXECUTE IMMEDIATE 'ALTER USER ' || '&v_app_user' || ' IDENTIFIED BY "' || '&v_app_pass' || '"';
  END IF;
  EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO ' || '&v_app_user';
  EXECUTE IMMEDIATE 'ALTER USER ' || '&v_app_user' || ' QUOTA UNLIMITED ON USERS';
END;
/

-- 3. Tài khoản phục vụ kịch bản Brute-force Hydra (KB2)
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM dba_users WHERE username = UPPER('&v_bf_user');
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER ' || '&v_bf_user' || ' IDENTIFIED BY "' || '&v_bf_pass' || '" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP PROFILE LAB_BF_PROFILE';
  ELSE
    EXECUTE IMMEDIATE 'ALTER USER ' || '&v_bf_user' || ' IDENTIFIED BY "' || '&v_bf_pass' || '" PROFILE LAB_BF_PROFILE';
  END IF;
  EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO ' || '&v_bf_user';
END;
/

-- 4. Tạo bảng STUDENTS và GRADES trong schema ứng dụng
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM dba_tables WHERE owner = UPPER('&v_app_user') AND table_name = 'GRADES';
  IF v_cnt > 0 THEN
    EXECUTE IMMEDIATE 'DROP TABLE ' || '&v_app_user' || '.GRADES CASCADE CONSTRAINTS PURGE';
  END IF;

  SELECT COUNT(*) INTO v_cnt FROM dba_tables WHERE owner = UPPER('&v_app_user') AND table_name = 'STUDENTS';
  IF v_cnt > 0 THEN
    EXECUTE IMMEDIATE 'DROP TABLE ' || '&v_app_user' || '.STUDENTS CASCADE CONSTRAINTS PURGE';
  END IF;
END;
/

CREATE TABLE &v_app_user..STUDENTS (
  student_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_code VARCHAR2(20)  NOT NULL UNIQUE,
  full_name    VARCHAR2(100) NOT NULL,
  class_name   VARCHAR2(30)  NOT NULL,
  email        VARCHAR2(100) NOT NULL,
  username     VARCHAR2(50)  NOT NULL UNIQUE,
  password     VARCHAR2(100) NOT NULL,
  gpa          NUMBER(3,2)
);

CREATE TABLE &v_app_user..GRADES (
  grade_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id    NUMBER        NOT NULL,
  course_code   VARCHAR2(20)  NOT NULL,
  course_name   VARCHAR2(100) NOT NULL,
  midterm_score NUMBER(4,2)   NOT NULL,
  final_score   NUMBER(4,2)   NOT NULL,
  total_score   NUMBER(4,2)   NOT NULL,
  letter_grade  VARCHAR2(5)   NOT NULL,
  semester      VARCHAR2(20)  NOT NULL,
  CONSTRAINT fk_grades_student FOREIGN KEY (student_id) REFERENCES &v_app_user..STUDENTS(student_id)
);

-- Public synonym để các truy vấn không cần ghi prefix schema vẫn chạy và được audit
CREATE OR REPLACE PUBLIC SYNONYM STUDENTS FOR &v_app_user..STUDENTS;
CREATE OR REPLACE PUBLIC SYNONYM GRADES   FOR &v_app_user..GRADES;

-- Cấp quyền đọc cho tài khoản GV_USER (phục vụ truy vấn sau brute-force KB2)
GRANT SELECT ON &v_app_user..STUDENTS TO &v_bf_user;
GRANT SELECT ON &v_app_user..GRADES   TO &v_bf_user;

